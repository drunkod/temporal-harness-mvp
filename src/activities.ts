import { readFile, writeFile, mkdir, stat, realpath } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, join, basename, dirname, relative } from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import type { Task, Packet, Receipt } from './protocol.js';
const hash = (v: string) => createHash('sha256').update(v).digest('hex');
const git = (cwd: string, ...args: string[]) => {
  const r = spawnSync('git', args, { cwd, encoding: 'utf8', timeout: 20000 });
  if (r.status !== 0) throw new Error('git ' + args[0] + ': ' + (r.stderr || r.stdout).trim());
  return r.stdout.trim();
};
const workspaceRoot = (root: string) => join(resolve(root), '.state');
const knownProjects = ['alpha', 'beta']; // Only our disposable fixtures. Never scan Documents/work blindly.
function assertSafeRoot(root: string, repo: string): void {
  const base = resolve(root, 'examples', 'projects');
  if (!knownProjects.some(x => resolve(base, x) === resolve(repo))) throw new Error('unapproved test repo');
}
function exactContent(task: Task): string {
  return '# Verified greeting: ' + task.project + '\n\n'
   + 'This file was generated by the deterministic MVP spec compiler, '
   + 'applied in an isolated Git worktree, and independently verified before promotion.\n\n'
   + '- Task: ' + task.taskId + '\n'
   + '- Project: ' + task.project + '\n'
   + '- Expected greeting: Hello from ' + task.project + '!\n';
}
export async function nextTask(root: string): Promise<Task | null> {
  for (const project of knownProjects) {
    const repo = join(resolve(root), 'examples', 'projects', project);
    assertSafeRoot(root, repo);
    if (!existsSync(join(repo, '.git'))) continue;
    const file = await readFile(join(repo, 'TASKS.md'), 'utf8');
    const line = file.match(/^- \[ \] ([a-z0-9-]+): (.+)$/m);
    if (!line) continue;
    if (git(repo, 'status', '--porcelain')) throw new Error('Fixture repo has uncommitted changes: ' + project);
    return { project, repo, taskId: line[1], title: line[2], head: git(repo, 'rev-parse', 'HEAD') };
  }
  return null;
}
export async function compilePacket(root: string, task: Task): Promise<Packet> {
  assertSafeRoot(root, task.repo);
  if (task.head !== git(task.repo, 'rev-parse', 'HEAD')) throw new Error('stale Git HEAD');
  const content = exactContent(task);
  const input = { project: task.project, taskId: task.taskId, title: task.title,
    repo: task.repo, head: task.head, outputRel: 'OUTPUT.md', content, contentSha256: hash(content) };
  const packetSha256 = hash(JSON.stringify(input));
  const packets = join(workspaceRoot(root), 'packets');
  await mkdir(packets, { recursive: true });
  const packetFile = join(packets, task.taskId + '-' + packetSha256.slice(0, 12) + '.json');
  const packet: Packet = { ...task, outputRel: 'OUTPUT.md', content, contentSha256: hash(content),
    packetSha256, packetFile };
  await writeFile(packetFile, JSON.stringify(packet, null, 2) + '\n');
  return packet;
}
export async function classifyJev(packet: Packet, enabled: boolean): Promise<string> {
  if (!enabled) return 'disabled';
  try {
    // Reuse the exact working Jev/OpenCode-Zen integration; never read or log the secret.
    const source = process.env.JEV_CORE_PATH
      ?? '/Users/test/nix-config/ai-tools/opencode/plugin/jev-core.mjs';
    const mod = await import(pathToFileURL(source).href);
    const questions = { demo_risk: {
      type: 'choice',
      instructions: 'Classify this planned file operation, not its business value.',
      criteria: {
        low: 'An isolated disposable test Git repository; writes only OUTPUT.md with an exact spec.',
        review: 'Uncertain or potentially sensitive filesystem effect requiring review.'
      }
    }};
    const response = await mod.askSystemOne({
      state: 'MVP fixture=' + packet.project + '; target OUTPUT.md; task=' + packet.title
        + '; isolated worktree; no network publish, no secrets, no real projects.',
      questions, timeoutMs: 7000,
    });
    const choice = response.answers.demo_risk.choice;
    const confidence = response.answers.demo_risk.confidence;
    return 'OpenCode Zen Jev ' + choice + ' confidence=' + confidence;
  } catch (e) {
    return 'Jev unavailable/advisory skipped: ' + (e instanceof Error ? e.name : 'unknown');
  }
}
export async function browserDryRun(packet: Packet): Promise<string> {
  const args = ['chatgpt', 'browser-consult', '--repo', packet.repo,
    '--title', 'mvp-' + packet.taskId,
    '--prompt', 'Review this disposable demo specification without modifying code: '
      + packet.title + '. Expected output: ' + packet.outputRel,
    '--dry-run'];
  const binary = process.env.REPO_HARNESS_BIN ?? '/etc/profiles/per-user/test/bin/repo-harness';
  const p = spawnSync(binary, args, { encoding: 'utf8', timeout: 45000 });
  if (p.status !== 0) return 'dry-run unavailable: '
    + (p.error?.message || p.stderr || p.stdout || 'exit=' + p.status).slice(0, 240).trim();
  // Browser stdout is not a final model answer; require a persisted session record.
  const result = JSON.parse(p.stdout || '{}') as { status?: string; sessionId?: string };
  const session = result.sessionId;
  const sessions = join(packet.repo, '.ai', 'harness', 'chatgpt', 'sessions');
  if (result.status !== 'dry_run' || !session || !/^chgpt_[a-zA-Z0-9_-]+$/.test(session))
    return 'dry-run incomplete: no validated session metadata';
  const meta = join(sessions, session, 'meta.json');
  if (!existsSync(meta)) return 'dry-run incomplete: metadata file missing';
  const saved = JSON.parse(await readFile(meta, 'utf8')) as { status?: string };
  if (saved.status !== 'dry_run') return 'dry-run incomplete: status=' + saved.status;
  return 'dry-run session saved: ' + session;
}
export async function executeVerifyPromote(
  root: string, packet: Packet, jev: string, browser: string
): Promise<Receipt> {
  assertSafeRoot(root, packet.repo);
  const expected = hash(packet.content);
  if (expected !== packet.contentSha256) throw new Error('spec integrity violation');
  const basic = { project: packet.project, repo: packet.repo, taskId: packet.taskId,
    packetSha256: packet.packetSha256, contentSha256: packet.contentSha256, jev, browser };
  const claimDir = join(workspaceRoot(root), 'claims');
  const receipts = join(workspaceRoot(root), 'receipts');
  const worktrees = join(workspaceRoot(root), 'worktrees');
  await Promise.all([mkdir(claimDir, { recursive: true }), mkdir(receipts, { recursive: true }),
    mkdir(worktrees, { recursive: true })]);
  const claim = join(claimDir, packet.taskId + '.json');
  const receiptPath = join(receipts, packet.taskId + '.json');
  if (existsSync(receiptPath)) {
    const old = JSON.parse(await readFile(receiptPath, 'utf8')) as Receipt;
    if (old.packetSha256 === packet.packetSha256) return old;
    throw new Error('previous receipt has different spec');
  }
  if (existsSync(claim)) {
    return { ...basic, gitCommit: '', worktree: '', verdict: 'indeterminate' };
  }
  await writeFile(claim, JSON.stringify({ packetSha256: packet.packetSha256, started: new Date().toISOString() }), { flag: 'wx' });
  const worktree = join(worktrees, packet.taskId + '-' + randomUUID().slice(0, 8));
  try {
    if (git(packet.repo, 'rev-parse', 'HEAD') !== packet.head) throw new Error('stale head; fail closed');
    git(packet.repo, 'worktree', 'add', '--detach', worktree, packet.head);
    // Codex TYPEWRITER substitute for this first proof: apply the exact planner packet.
    // This guarantees no model improvisation and keeps the executable MVP offline.
    await writeFile(join(worktree, packet.outputRel), packet.content, { flag: 'wx' });
    const found = await readFile(join(worktree, packet.outputRel), 'utf8');
    if (hash(found) !== expected) throw new Error('independent sha256 verification failed');
    const changes = git(worktree, 'status', '--porcelain');
    if (changes !== '?? OUTPUT.md') throw new Error('unexpected writes: ' + changes);
    git(worktree, 'add', '--', packet.outputRel);
    const staged = git(worktree, 'diff', '--cached', '--name-only');
    if (staged !== packet.outputRel) throw new Error('unexpected diff scope: ' + staged);
    git(worktree, '-c', 'user.name=Temporal MVP', '-c', 'user.email=mvp@localhost',
      'commit', '-qm', 'mvp: ' + packet.taskId);
    const commit = git(worktree, 'rev-parse', 'HEAD');
    // Promote only verified Git commit into the disposable project.
    git(packet.repo, 'cherry-pick', commit);
    const onMain = await readFile(join(packet.repo, packet.outputRel), 'utf8');
    if (hash(onMain) !== expected) throw new Error('promotion failed final hash verification');
    const todo = join(packet.repo, 'TASKS.md');
    const previous = await readFile(todo, 'utf8');
    const pending = '- [ ] ' + packet.taskId + ':';
    if (!previous.includes(pending)) throw new Error('TODO task changed unexpectedly');
    await writeFile(todo, previous.replace(pending, '- [x] ' + packet.taskId + ':'));
    git(packet.repo, 'add', '--', 'TASKS.md');
    git(packet.repo, '-c', 'user.name=Temporal MVP', '-c', 'user.email=mvp@localhost',
      'commit', '-qm', 'mvp: mark ' + packet.taskId + ' verified');
    const receipt: Receipt = { ...basic, worktree, gitCommit: git(packet.repo, 'rev-parse', 'HEAD'), verdict: 'verified' };
    await writeFile(receiptPath, JSON.stringify(receipt, null, 2) + '\n', { flag: 'wx' });
    return receipt;
  } catch (e) {
    const receipt: Receipt = { ...basic, worktree, gitCommit: '', verdict: 'indeterminate' };
    await writeFile(receiptPath + '.error', String(e).slice(0, 2000));
    return receipt;
  } finally {
    if (existsSync(worktree)) {
      try { git(packet.repo, 'worktree', 'remove', '--force', worktree); } catch {}
    }
  }
}
